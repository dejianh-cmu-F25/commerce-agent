"""Render ``evals/report.md`` from the benchmark artifacts (features 022, 023).

The report merges the keyless artifacts (regenerated by the gate) with the
opt-in real-model artifacts (regenerated only by ``--real`` runs), so a keyless
run never clobbers the real numbers. Raw JSON is not committed.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYLESS = ROOT / "evals" / "results-keyless.json"
REAL = ROOT / "evals" / "results-real.json"
REPORT = ROOT / "evals" / "report.md"
CHANGE_LOG = ROOT / "specs" / "change-log.json"
RESULTS = ROOT / "specs" / "RESULTS.md"
CHANGE_LOG_START = "<!-- change-log:start -->"
CHANGE_LOG_END = "<!-- change-log:end -->"


def _load(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError:
        return {}


def _retrieval_section(retrieval: dict) -> list[str]:
    if not retrieval:
        return []
    k = retrieval["k"]
    lines = [
        "## Retrieval benchmark (keyless)",
        "",
        f"Metric definitions: **hit-rate@{k}** = at least one expected document in the "
        f"top {k}; **recall@{k}** = fraction of expected documents found; **MRR** = mean "
        "reciprocal rank of the first hit.",
        "",
        f"Queries: {retrieval['cases']} (easy / medium / hard) over `config/knowledge/` "
        "(shipping, returns, warranty).",
        "",
        f"| Config | hit-rate@{k} | recall@{k} | MRR | avg ms |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for config, metrics in retrieval["configs"].items():
        lines.append(
            f"| `{config}` | {metrics['hit_rate']:.3f} | {metrics['recall']:.3f} | "
            f"{metrics['mrr']:.3f} | {metrics.get('avg_ms', 0.0):.1f} |"
        )
    lines.append("")

    levels = sorted(
        {
            level
            for metrics in retrieval["configs"].values()
            for level in metrics.get("by_difficulty", {})
        }
    )
    if levels:
        header = "| Config | " + " | ".join(f"{level} hit@{k}" for level in levels) + " |"
        divider = "| --- | " + " | ".join("---:" for _ in levels) + " |"
        lines += [f"hit-rate@{k} by difficulty:", "", header, divider]
        for config, metrics in retrieval["configs"].items():
            cells = " | ".join(
                f"{metrics['by_difficulty'].get(level, 0.0):.3f}" for level in levels
            )
            lines.append(f"| `{config}` | {cells} |")
        lines.append("")
    return lines


def _ablation_section(ablation: dict) -> list[str]:
    configs = ablation.get("configs")
    if not configs:
        return []
    lines = [
        "## Feature ablation (keyless)",
        "",
        "Each configuration runs the same gold scenarios (scripted model); the delta is "
        "vs the naked baseline, with a 95% bootstrap CI and an exact McNemar p-value.",
        "",
        "| Config | Passed | Pass rate | Delta vs naked | 95% CI | p (McNemar) |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, metrics in configs.items():
        ci = f"[{metrics['ci_low']:.3f}, {metrics['ci_high']:.3f}]" if "ci_low" in metrics else "—"
        p_value = f"{metrics.get('p_value', 1.0):.3f}" if "p_value" in metrics else "—"
        lines.append(
            f"| `{name}` | {metrics['passed']}/{metrics['total']} | "
            f"{metrics['pass_rate']:.3f} | {metrics.get('delta', 0.0):+.3f} | "
            f"{ci} | {p_value} |"
        )
    lines.append("")
    return lines


def _data_quality_section(data_quality: dict) -> list[str]:
    if not data_quality:
        return []
    return [
        "## Data quality (keyless)",
        "",
        "Boundary normalizers scored against a labeled dirty-input set "
        "(`evals/data_quality_set.py`): currency symbols, thousands separators, "
        '"out of stock", padding, control characters, negatives, missing fields.',
        "",
        "| Cases | Before (naive) | After (normalized) |",
        "| ---: | ---: | ---: |",
        f"| {data_quality['cases']} | {data_quality.get('baseline_accuracy', 0.0):.3f} | "
        f"{data_quality['accuracy']:.3f} |",
        "",
    ]


def _adversarial_section(adversarial: dict) -> list[str]:
    if not adversarial:
        return []
    return [
        "## Adversarial input (keyless)",
        "",
        "The deterministic input guard, scored against a labeled set of hostile and "
        "benign messages (`evals/adversarial_set.py`): injection, prompt extraction, "
        "unicode obfuscation, oversized input, and benign controls.",
        "",
        "| Cases | Before (no guard) | After (guarded) |",
        "| ---: | ---: | ---: |",
        f"| {adversarial['cases']} | "
        f"{adversarial.get('baseline_safe_rate', 0.0):.3f} | {adversarial['safe_rate']:.3f} |",
        "",
    ]


def _agent_section(agent: dict) -> list[str]:
    if not agent:
        return []
    lines = [
        "## Agent evaluation (real model, opt-in)",
        "",
        f"- Model: `{agent.get('model', '?')}` · prompt: `{agent.get('prompt_hash', '?')}` · "
        f"seeds: {agent.get('seeds', '?')} · judge: `{agent.get('judge_model', '?')}`",
        f"- Generated: {agent.get('generated', '?')}",
        f"- Command: `{agent.get('command', '')}`",
        "",
    ]
    reliability = agent.get("reliability", {})
    if reliability:
        lines += [
            f"Reliability over {reliability['tasks']} tasks × {agent.get('seeds', '?')} "
            f"runs ({reliability['runs']} runs, {reliability['successes']} successes):",
            "",
            "| Pass@1 | Pass@k | Best@k | Pass^k |",
            "| ---: | ---: | ---: | ---: |",
            f"| {reliability['pass_at_1']:.3f} | {reliability['pass_at_k']:.3f} | "
            f"{reliability['best_at_k']:.3f} | {reliability['pass_pow_k']:.3f} |",
            "",
        ]
        ci = reliability.get("pass_at_1_ci")
        if ci:
            lines += [f"Pass@1 95% CI: [{ci[0]:.3f}, {ci[1]:.3f}] (bootstrap).", ""]
    per_task = agent.get("per_task", {})
    if per_task:
        lines += [
            "Per-template reliability:",
            "",
            "| Template | Pass@1 | Pass@k | Pass^k |",
            "| --- | ---: | ---: | ---: |",
        ]
        for name, metrics in per_task.items():
            lines.append(
                f"| `{name}` | {metrics['pass_at_1']:.3f} | {metrics['pass_at_k']:.3f} | "
                f"{metrics['pass_pow_k']:.3f} |"
            )
        lines.append("")
    process = agent.get("process", {})
    if process:
        lines += [
            "Process metrics (per run):",
            "",
            "| steps | tool ok/err | ungrounded | avg ms | p95 ms | prompt tok | "
            "completion tok | cache hit | cost CNY |",
            "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
            f"| {process.get('avg_steps', 0):.2f} | {process.get('tool_ok', 0)}/"
            f"{process.get('tool_error', 0)} | {process.get('ungrounded_attempts', 0)} | "
            f"{process.get('avg_latency_ms', 0):.0f} | {process.get('p95_latency_ms', 0):.0f} | "
            f"{process.get('prompt_tokens', 0)} | {process.get('completion_tokens', 0)} | "
            f"{process.get('cache_hit_tokens', 0)} | {process.get('cost_cny', 0.0):.4f} |",
            "",
        ]
    failures = agent.get("failures", {})
    if failures:
        lines += [
            "Failure attribution (first error):",
            "",
            "| Category | Count |",
            "| --- | ---: |",
        ]
        for category, count in failures.items():
            lines.append(f"| `{category}` | {count} |")
        lines.append("")
    judge = agent.get("judge", {})
    if judge and judge.get("graded"):
        lines += [
            f"Rubric judge: graded {judge['graded']} answers, {judge.get('vetoes', 0)} vetoes.",
            "",
            "| Dimension | Avg (1-4) |",
            "| --- | ---: |",
        ]
        for dimension, value in judge.get("avg_scores", {}).items():
            lines.append(f"| {dimension} | {value:.2f} |")
        lines.append("")
    return lines


def _change_log_table(entries: list[dict]) -> str:
    lines = [
        "| Date | Change | Area | Class | What changed | Metric | Before → After "
        "| Guardrails | Verdict | Evidence |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in entries:
        before, after = entry.get("before"), entry.get("after")
        if before is not None and after is not None:
            delta = f"{before} → {after}"
        else:
            delta = entry.get("note") or "—"
        lines.append(
            f"| {entry['date']} | {entry['change']} | {entry['area']} | "
            f"`{entry['class']}` | {entry['what']} | {entry.get('metric') or '—'} | "
            f"{delta} | {entry.get('guardrails') or '—'} | {entry['verdict']} | "
            f"`{entry['evidence']}` |"
        )
    return "\n".join(lines)


def _change_log_section(entries: list[dict]) -> list[str]:
    if not entries:
        return []
    return ["## Change log", "", _change_log_table(entries), ""]


def render() -> str:
    keyless = _load(KEYLESS)
    real = _load(REAL)
    lines = [
        "# Evaluation report",
        "",
        "Generated by `uv run python evals/report.py --write` on "
        f"{datetime.now(UTC).date().isoformat()}.",
        "",
        "- Embedding: keyless `hash` (256 dims).",
        "- Vector stores: in-process `memory` and persistent `chroma`.",
        "- Raw artifacts (`evals/results-*.json`) are regenerated and not committed.",
        "",
    ]
    lines += _retrieval_section(keyless.get("retrieval", {}))
    lines += _ablation_section(keyless.get("ablation", {}))
    lines += _data_quality_section(keyless.get("data_quality", {}))
    lines += _adversarial_section(keyless.get("adversarial", {}))
    lines += _agent_section(real.get("agent", {}))
    lines += _change_log_section(_load(CHANGE_LOG).get("entries", []))
    return "\n".join(lines).rstrip() + "\n"


def _update_results_change_log(entries: list[dict]) -> None:
    """Refresh the generated change-log block inside specs/RESULTS.md."""
    if not RESULTS.exists():
        return
    text = RESULTS.read_text()
    if CHANGE_LOG_START not in text or CHANGE_LOG_END not in text:
        return
    start = text.index(CHANGE_LOG_START) + len(CHANGE_LOG_START)
    end = text.index(CHANGE_LOG_END)
    block = "\n" + _change_log_table(entries) + "\n"
    RESULTS.write_text(text[:start] + block + text[end:])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="write evals/report.md")
    args = parser.parse_args()
    text = render()
    if args.write:
        REPORT.write_text(text)
        _update_results_change_log(_load(CHANGE_LOG).get("entries", []))
        print(f"wrote {REPORT} and refreshed the change log in {RESULTS}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
