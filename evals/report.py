"""Render ``evals/report.md`` from the benchmark artifacts (features 022, 023).

The report merges the keyless artifacts (regenerated by the gate) with the
opt-in real-model artifacts (regenerated only by ``--real`` runs), so a keyless
run never clobbers the real numbers. Raw JSON is not committed.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYLESS = ROOT / "evals" / "results-keyless.json"
REAL = ROOT / "evals" / "results-real.json"
REPORT = ROOT / "evals" / "report.md"


def _load(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError:
        return {}


def _retrieval_section(retrieval: dict) -> list[str]:
    if not retrieval:
        return ["_No retrieval results yet._", ""]
    k = retrieval["k"]
    lines = [
        f"Metric definitions: **hit-rate@{k}** = at least one expected document in the "
        f"top {k}; **recall@{k}** = fraction of expected documents found; **MRR** = mean "
        "reciprocal rank of the first hit.",
        "",
        f"Queries: {retrieval['cases']} (easy / medium / hard) over `config/knowledge/` "
        "(shipping, returns, warranty).",
        "",
        f"| Config | hit-rate@{k} | recall@{k} | MRR | avg ms |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for config, metrics in retrieval["configs"].items():
        lines.append(
            f"| `{config}` | {metrics['hit_rate']:.3f} | {metrics['recall']:.3f} | "
            f"{metrics['mrr']:.3f} | {metrics.get('avg_ms', 0.0):.1f} |"
        )
    lines.append("")

    levels = sorted(
        {
            level
            for metrics in retrieval["configs"].values()
            for level in metrics.get("by_difficulty", {})
        }
    )
    if levels:
        header = "| Config | " + " | ".join(f"{level} hit@{k}" for level in levels) + " |"
        divider = "| --- | " + " | ".join("---:" for _ in levels) + " |"
        lines += [f"hit-rate@{k} by difficulty:", "", header, divider]
        for config, metrics in retrieval["configs"].items():
            cells = " | ".join(
                f"{metrics['by_difficulty'].get(level, 0.0):.3f}" for level in levels
            )
            lines.append(f"| `{config}` | {cells} |")
        lines.append("")
    return lines


def render() -> str:
    keyless = _load(KEYLESS)
    real = _load(REAL)
    lines = [
        "# Evaluation report",
        "",
        "Generated by `uv run python evals/report.py --write` on "
        f"{datetime.now(UTC).date().isoformat()}.",
        "",
        "- Embedding: keyless `hash` (256 dims).",
        "- Vector stores: in-process `memory` and persistent `chroma`.",
        "- Raw artifacts (`evals/results-*.json`) are regenerated and not committed.",
        "",
        "## Retrieval benchmark (keyless)",
        "",
    ]
    lines += _retrieval_section(keyless.get("retrieval", {}))
    lines += _real_sections(real)
    return "\n".join(lines).rstrip() + "\n"


def _real_sections(real: dict) -> list[str]:
    """Real-model sections; extended by feature 023 (agent reliability, cost)."""
    if not real:
        return []
    return []


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="write evals/report.md")
    args = parser.parse_args()
    text = render()
    if args.write:
        REPORT.write_text(text)
        print(f"wrote {REPORT}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
